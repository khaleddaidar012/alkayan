let currentLang = localStorage.getItem('alkayan_lang') || 'ar';
let currentPage = 'dashboard';
let currentSection = 'dashboard';

function setDirection(lang) {
  if (lang === 'ar') {
    document.documentElement.dir = 'rtl';
    document.documentElement.lang = 'ar';
  } else {
    document.documentElement.dir = 'ltr';
    document.documentElement.lang = 'en';
  }
}

function getSectionKeys(section) {
  return (i18n[currentLang] && i18n[currentLang][section]) || null;
}

function resolveKey(section, key) {
  const sectionKeys = getSectionKeys(section);
  if (sectionKeys && typeof sectionKeys[key] === 'string') {
    return sectionKeys[key];
  }
  const navKeys = getSectionKeys('nav');
  if (navKeys && typeof navKeys[key] === 'string') {
    return navKeys[key];
  }
  const langObj = i18n[currentLang] || {};
  if (langObj[key] && typeof langObj[key] === 'string') {
    return langObj[key];
  }
  return null;
}

function applyTranslation(page, section) {
  const sectionToUse = section || currentSection || page || 'dashboard';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = resolveKey(sectionToUse, key);
    if (value !== null) {
      el.textContent = value;
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const value = resolveKey(sectionToUse, key);
    if (value !== null) {
      el.placeholder = value;
    }
  });
}

function switchLang() {
  currentLang = currentLang === 'ar' ? 'en' : 'ar';
  localStorage.setItem('alkayan_lang', currentLang);
  setDirection(currentLang);
  applyTranslation(currentPage, currentSection);
  updateLangToggle();
  updateThemeToggle();
}

function updateLangToggle() {
  const btn = document.getElementById('langToggle') || document.getElementById('langToggle2');
  if (btn) {
    const label = resolveKey(currentSection, 'langSwitch');
    btn.innerHTML = `<span class="icon">🌐</span> ${label !== null ? label : ''}`;
  }
}

function initI18n(page, section) {
  const savedLang = localStorage.getItem('alkayan_lang');
  if (savedLang === 'ar' || savedLang === 'en') {
    currentLang = savedLang;
  } else if (savedLang) {
    localStorage.setItem('alkayan_lang', 'ar');
    currentLang = 'ar';
  }
  currentPage = page || 'dashboard';
  currentSection = section || page || 'dashboard';
  setDirection(currentLang);
  applyTranslation(currentPage, currentSection);
  updateLangToggle();
}
